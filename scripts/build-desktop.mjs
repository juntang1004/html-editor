import fs from 'node:fs';
import path from 'node:path';
import {spawnSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';
import './prepare-desktop.mjs';
import {packageNotices} from './package-notices.mjs';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const cache=path.join(process.env.LOCALAPPDATA,'SlideStudioDev/cargo-target');
const env={...process.env,PATH:path.join(process.env.USERPROFILE,'.cargo/bin')+';'+process.env.PATH,CARGO_TARGET_DIR:cache};
const cli=path.join(root,'node_modules/@tauri-apps/cli/tauri.js');
const result=spawnSync(process.execPath,[cli,'build','--no-bundle'],{cwd:root,env,stdio:'inherit'});
if(result.status!==0)process.exit(result.status||1);
const output=path.join(root,'artifacts/HTML-Slide-Studio-Windows-x64');
fs.mkdirSync(output,{recursive:true});
fs.copyFileSync(path.join(cache,'release/html-slide-studio.exe'),path.join(output,'HTML Slide Studio.exe'));
fs.cpSync(path.join(root,'src-tauri/resources'),path.join(output,'resources'),{recursive:true});
packageNotices(root,output);
fs.copyFileSync(path.join(root,'docs/user-guide.ko.md'),path.join(output,'사용안내.md'));
fs.copyFileSync(path.join(root,'tests/fixtures/layout-and-animation.html'),path.join(output,'예제-슬라이드.html'));
fs.copyFileSync(path.join(root,'release.json'),path.join(output,'release.json'));
fs.writeFileSync(path.join(output,'시작하기.txt'),'HTML Slide Studio.exe를 실행하세요.\r\nresources 폴더는 실행 파일 옆에 그대로 두세요.\r\nWindows 10/11 x64 및 Microsoft Edge WebView2 Runtime이 필요합니다.\r\nPDF 저장은 파일 > PDF로 저장에서 Microsoft Print to PDF를 선택합니다.\r\nAPI 키는 배포본에 포함되지 않습니다.\r\n');
console.log('Portable Windows app: '+output);
